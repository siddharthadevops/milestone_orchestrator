class TestRenderMilestone(unittest.TestCase):
    def setUp(self):
        self.state = make_state()
        self.text = ledgers.render_milestone(self.state)

    def test_generated_marker_leads_the_file(self):
        self.assertTrue(self.text.startswith(GENERATED_MARKER))
        self.assertIn("do not edit", self.text)

    def test_status_goal_and_slice_table(self):
        self.assertIn("# Milestone", self.text)
        self.assertIn("Status: **closed**", self.text)
        self.assertIn("Ship a tiny calculator with tests", self.text)
        self.assertIn("| 01 | Calculator core |", self.text)

    def test_unit_rows_with_seal_summaries_and_gate_commit(self):
        self.assertIn("| skeleton | sealed | 6 | a1:pass | abc1234 |", self.text)
        self.assertIn(
            "| slice_doc-01 (Calculator core) | sealed | 0 | - | - |", self.text
        )
        # The invalidated attempt renders as "invalid", the findings attempt
        # as "findings", the clean one as "pass"; no gate commit -> "-".
        self.assertIn(
            "| slice_impl-01 (Calculator core) | sealed | 3 "
            "| a1:invalid, a2:findings, a3:pass | - |",
            self.text,
        )

    def test_no_failure_section_without_failure(self):
        self.assertNotIn("## Failure", self.text)

    def test_failure_section_rendered_when_failed(self):
        state = make_state()
        state["milestone"]["status"] = "failed"
        state["failure"] = {
            "at": "2026-01-03T00:00:00+0000",
            "unit": "slice_impl-01",
            "reason": "boom",
        }
        text = ledgers.render_milestone(state)
        self.assertIn("Status: **failed**", text)
        self.assertIn("## Failure", text)
        self.assertIn("- at: 2026-01-03T00:00:00+0000", text)
        self.assertIn("- unit: slice_impl-01", text)
        self.assertIn("- reason: boom", text)


class TestRenderReviewLog(unittest.TestCase):
    def setUp(self):
        self.state = make_state()
        self.text = ledgers.render_review_log(self.state)

    def test_generated_marker_and_heading(self):
        self.assertTrue(self.text.startswith(GENERATED_MARKER))
        self.assertIn("# Review Log", self.text)

    def test_unit_sections_present(self):
        self.assertIn("## skeleton", self.text)
        self.assertIn("## slice_doc-01 (Calculator core)", self.text)
        self.assertIn("## slice_impl-01 (Calculator core)", self.text)

    def test_draft_line(self):
        self.assertIn(
            "- draft: kind `draft_skeleton`, artifact `docs/skeleton.md` "
            "(raw: `.orchestrator/raw/skeleton-draft.txt`)",
            self.text,
        )

    def test_reported_review_round_row(self):
        # Reviewer findings carry no disposition: they count as "reported".
        self.assertIn(
            "| skeleton-codex-r1 | review_round | codex | 1 "
            "| 1 reported "
            "| `.orchestrator/raw/skeleton-codex-r1.txt` |",
            self.text,
        )

    def test_fix_round_rows_with_triage_and_consultation(self):
        self.assertIn(
            "| skeleton-codex-r2 | fix_findings | codex | 1 "
            "| 1 fixed "
            "| `.orchestrator/raw/skeleton-fix1.txt` |",
            self.text,
        )
        # The rejection carries its consultation.
        self.assertIn(
            "| skeleton-codex-r4 | fix_findings | codex | 1 "
            "| 1 rejected (1 consulted) "
            "| `.orchestrator/raw/skeleton-fix2.txt` |",
            self.text,
        )

    def test_clean_delta_review_row(self):
        self.assertIn(
            "| skeleton-codex-r3 | delta_review | codex | 0 | clean "
            "| `.orchestrator/raw/skeleton-delta1.txt` |",
            self.text,
        )

    def test_seal_attempt_headings_cover_all_outcomes(self):
        self.assertIn("### Seal attempt a1 — PASSED", self.text)  # skeleton
        self.assertIn("### Seal attempt a1 — INVALIDATED", self.text)
        self.assertIn("### Seal attempt a2 — findings", self.text)
        self.assertIn("### Seal attempt a3 — PASSED", self.text)

    def test_invalidated_attempt_details(self):
        self.assertIn(
            "- invalidated: seal half codex modified the workspace; "
            "its output is invalid",
            self.text,
        )
        self.assertIn(
            "- codex half: 0 finding(s); workspace_modified=True; "
            "raw `.orchestrator/raw/slice_impl-01-seal-a1-codex.txt`",
            self.text,
        )

    def test_findings_attempt_lists_each_finding(self):
        self.assertIn(
            "- claude half: 1 finding(s); workspace_modified=False; "
            "raw `.orchestrator/raw/slice_impl-01-seal-a2-claude.txt`",
            self.text,
        )
        self.assertIn("  - [P3] workspace lacks a README", self.text)

    def test_requeued_implementation_debt_is_not_republished(self):
        state = make_state()
        state["events"] = []
        impl = state["units"][2]
        impl["status"] = st.U_SEALING
        impl["debt"] = [{
            "id": "claude-F9",
            "severity": "P3",
            "summary": "historical implementation defect",
            "raised_by": "claude",
            "cleared_by": "codex",
            "reason": "previously deferred",
        }]

        st.requeue_implementation_debt(state)
        text = ledgers.render_review_log(state)

        self.assertEqual(len(impl["debt"]), 1)
        self.assertNotIn("historical implementation defect", text)
        self.assertNotIn("Deferred debt", text)


class TestRenderAdjudications(unittest.TestCase):
    def setUp(self):
        self.state = make_state()
        self.text = ledgers.render_adjudications(self.state)

    def test_generated_marker_and_heading(self):
        self.assertTrue(self.text.startswith(GENERATED_MARKER))
        self.assertIn("# Adjudicated Rejections", self.text)

    def test_entry_derived_from_the_rejected_fix_finding(self):
        # Entry id = "<source_round_id>/<finding_id>" — the review round
        # whose finding the fixer rejected, not the fix round's own id.
        self.assertIn("## [%s]" % ADJ_ID, self.text)
        self.assertIn("- unit: skeleton", self.text)
        self.assertIn("- severity: P3", self.text)
        self.assertIn(
            "- finding: goal wording is ambiguous about float support",
            self.text,
        )

    def test_rationale_comes_from_the_consultation_resolution(self):
        self.assertIn("- rationale: %s" % ADJ_RATIONALE, self.text)

    def test_prevention_line_rendered_when_present(self):
        self.assertIn(
            "- prevention: docs/skeleton.md (explicit float-support note "
            "added)",
            self.text,
        )

    def test_fixed_and_verification_findings_are_not_adjudications(self):
        # Only "rejected" dispositions enter the registry: the fixed F1 and
        # the fixed V1 must not appear.
        self.assertNotIn("skeleton-codex-r1/F1", self.text)
        self.assertNotIn("slice_impl-01-verify-pre_review-1/V1", self.text)
        self.assertEqual(self.text.count("## ["), 1)

    def test_no_prevention_line_when_absent(self):
        state = make_state()
        rejected = state["units"][0]["rounds"][4]["result"]["findings"][0]
        rejected["prevention"] = None
        text = ledgers.render_adjudications(state)
        self.assertIn("## [%s]" % ADJ_ID, text)
        self.assertNotIn("- prevention:", text)

    def test_missing_rationale_renders_placeholder(self):
        state = make_state()
        rejected = state["units"][0]["rounds"][4]["result"]["findings"][0]
        rejected["consultation"] = None
        text = ledgers.render_adjudications(state)
        self.assertIn("- rationale: (none)", text)

    def test_empty_case(self):
        state = make_state()
        # Strip the rejection: no adjudicated entries remain.
        state["units"][0]["rounds"] = state["units"][0]["rounds"][:4]
        text = ledgers.render_adjudications(state)
        self.assertTrue(text.startswith(GENERATED_MARKER))
        self.assertIn("# Adjudicated Rejections", text)
        self.assertIn("(none)", text)
        self.assertNotIn("## [", text)
        self.assertNotIn("Settled findings", text)


