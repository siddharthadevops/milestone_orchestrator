class TestGenerate(unittest.TestCase):
    def setUp(self):
        self.state = make_state()
        self.tmp = tempfile.TemporaryDirectory(prefix="orch-ledgers-")
        self.addCleanup(self.tmp.cleanup)
        self.ws = self.tmp.name

    def _read_all(self, rels):
        blobs = {}
        for rel in rels:
            with open(os.path.join(self.ws, rel), "rb") as fh:
                blobs[rel] = fh.read()
        return blobs

    def test_returns_relative_paths_under_docs(self):
        rels = ledgers.generate(self.state, self.ws)
        self.assertEqual(
            rels,
            [
                os.path.join("docs", "MILESTONE.md"),
                os.path.join("docs", "review-log.md"),
                os.path.join("docs", "adjudications.md"),
                os.path.join("docs", "closures", "slice-01.md"),
            ],
        )
        for rel in rels:
            self.assertFalse(os.path.isabs(rel), rel)
            self.assertTrue(os.path.isfile(os.path.join(self.ws, rel)), rel)

    def test_written_files_match_render_functions(self):
        rels = ledgers.generate(self.state, self.ws)
        blobs = self._read_all(rels)
        self.assertEqual(
            blobs[os.path.join("docs", "MILESTONE.md")].decode("utf-8"),
            ledgers.render_milestone(self.state),
        )
        self.assertEqual(
            blobs[os.path.join("docs", "review-log.md")].decode("utf-8"),
            ledgers.render_review_log(self.state),
        )
        self.assertEqual(
            blobs[os.path.join("docs", "adjudications.md")].decode("utf-8"),
            ledgers.render_adjudications(self.state),
        )
        self.assertEqual(
            blobs[os.path.join("docs", "closures", "slice-01.md")].decode("utf-8"),
            ledgers.render_closure(self.state, self.state["units"][2]),
        )

    def test_adjudications_file_carries_the_registry_entry(self):
        ledgers.generate(self.state, self.ws)
        with open(
            os.path.join(self.ws, "docs", "adjudications.md"), encoding="utf-8"
        ) as fh:
            text = fh.read()
        self.assertIn("## [%s]" % ADJ_ID, text)
        self.assertIn(ADJ_RATIONALE, text)

    def test_generated_marker_in_every_file(self):
        rels = ledgers.generate(self.state, self.ws)
        for rel, blob in self._read_all(rels).items():
            self.assertIn(GENERATED_MARKER.encode("utf-8"), blob, rel)

    def test_deterministic_two_calls_identical_bytes(self):
        rels1 = ledgers.generate(self.state, self.ws)
        first = self._read_all(rels1)
        rels2 = ledgers.generate(self.state, self.ws)
        second = self._read_all(rels2)
        self.assertEqual(rels1, rels2)
        self.assertEqual(first, second)

    def test_closure_only_for_closed_slice_impl(self):
        # Not for slice_doc units, and not for a slice_impl that has no
        # closed_record yet.
        self.state["units"][2]["closed_record"] = None
        rels = ledgers.generate(self.state, self.ws)
        self.assertEqual(
            rels,
            [
                os.path.join("docs", "MILESTONE.md"),
                os.path.join("docs", "review-log.md"),
                os.path.join("docs", "adjudications.md"),
            ],
        )
        self.assertFalse(
            os.path.exists(os.path.join(self.ws, "docs", "closures"))
        )


class TestCanonicalLayout(unittest.TestCase):
    """docs_dir-driven layout: legacy "docs" keeps the flat MILESTONE.md
    shape; anything else uses the canonical milestone layout and
    maintains the parent milestone index."""

    def make_state(self, docs_dir=None, name=None):
        cfg = {"families_order": ["codex", "claude"]}
        if docs_dir:
            cfg["docs_dir"] = docs_dir
        return st.new_state("goal", "/ws", cfg, name=name)

    def test_legacy_paths(self):
        state = self.make_state()
        self.assertTrue(ledgers.is_legacy(state))
        self.assertEqual(ledgers.record_path(state), "docs/MILESTONE.md")
        self.assertEqual(ledgers.skeleton_path(state), "docs/skeleton.md")
        self.assertEqual(ledgers.slice_note_path(state, 3),
                         "docs/slice-03.md")
        self.assertIsNone(ledgers.index_path(state))

    def test_canonical_paths(self):
        state = self.make_state("implementation/milestones/{slug}",
                                name="Chat Tombstone Delete")
        d = "implementation/milestones/chat-tombstone-delete"
        self.assertFalse(ledgers.is_legacy(state))
        self.assertEqual(ledgers.docs_dir(state), d)
        self.assertEqual(ledgers.record_path(state), d + "/README.md")
        self.assertEqual(ledgers.skeleton_path(state), d + "/skeleton.md")
        self.assertEqual(ledgers.slice_note_path(state, 2),
                         d + "/slices/slice-02.md")
        self.assertEqual(ledgers.index_path(state),
                         "implementation/milestones/README.md")

    def test_index_upsert_preserves_hand_written_content(self):
        state = self.make_state("implementation/milestones/{slug}",
                                name="m one")
        first = ledgers.render_index_update(state, None)
        self.assertIn("# Milestone Index", first)
        self.assertIn(ledgers.INDEX_START, first)
        self.assertIn("| [m one](m-one/) | open |", first)
        # Hand-written prose around the block survives an update.
        hand = "Intro prose.\n\n" + first + "\nOutro prose.\n"
        state["milestone"]["status"] = "closed"
        st.append_event(state, "gate_commit", sha="abc")
        updated = ledgers.render_index_update(state, hand)
        self.assertIn("Intro prose.", updated)
        self.assertIn("Outro prose.", updated)
        self.assertIn("| closed |", updated)
        self.assertEqual(updated.count("| [m one](m-one/)"), 1)

    def test_index_upsert_keeps_other_milestones(self):
        a = self.make_state("implementation/milestones/{slug}", name="aaa")
        b = self.make_state("implementation/milestones/{slug}", name="bbb")
        text = ledgers.render_index_update(a, None)
        text = ledgers.render_index_update(b, text)
        self.assertIn("[aaa](aaa/)", text)
        self.assertIn("[bbb](bbb/)", text)

    def test_generate_canonical_writes_layout_and_index(self):
        state = self.make_state("implementation/milestones/{slug}",
                                name="demo run")
        with tempfile.TemporaryDirectory() as ws:
            written = ledgers.generate(state, ws)
            d = "implementation/milestones/demo-run"
            self.assertIn(d + "/README.md", written)
            self.assertIn("implementation/milestones/README.md", written)
            self.assertTrue(os.path.exists(
                os.path.join(ws, d, "README.md")))
            idx = open(os.path.join(
                ws, "implementation/milestones/README.md"),
                encoding="utf-8").read()
            self.assertIn("[demo run](demo-run/)", idx)


class TestIndexHardening(unittest.TestCase):
    def make_state(self, name):
        return st.new_state(
            "goal", "/ws",
            {"families_order": ["codex", "claude"],
             "docs_dir": "implementation/milestones/{slug}"},
            name=name,
        )

    def test_malformed_markers_raise_instead_of_eating_prose(self):
        state = self.make_state("m")
        hostile = ledgers.INDEX_END + "\nprose\n" + ledgers.INDEX_START
        with self.assertRaises(ledgers.LedgerError):
            ledgers.render_index_update(state, hostile)
        orphan = ledgers.INDEX_START + "\nprose after orphan start\n"
        with self.assertRaises(ledgers.LedgerError):
            ledgers.render_index_update(state, orphan)

    def test_pipe_in_name_neither_corrupts_nor_collides(self):
        a = self.make_state("api | phase 1")
        b = self.make_state("api | phase 2")
        text = ledgers.render_index_update(a, None)
        text = ledgers.render_index_update(b, text)
        self.assertIn("(api-phase-1/)", text)
        self.assertIn("(api-phase-2/)", text)
        # sanitized labels: no raw pipe inside the link text
        self.assertNotIn("[api | phase", text)

    def test_non_utf8_index_raises_ledger_error(self):
        state = self.make_state("m")
        with tempfile.TemporaryDirectory() as ws:
            idx_dir = os.path.join(ws, "implementation", "milestones")
            os.makedirs(idx_dir)
            with open(os.path.join(idx_dir, "README.md"), "wb") as fh:
                fh.write(b"# Index\n\xff\xfe broken\n")
            with self.assertRaises(ledgers.LedgerError):
                ledgers.generate(state, ws)


